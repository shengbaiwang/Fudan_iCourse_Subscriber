const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.SEA_TEST_URL || 'http://127.0.0.1:18976';
(async () => {
  const browser = await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL || 'chrome'});
  const context = await browser.newContext({viewport:{width:1440,height:960},acceptDownloads:true});
  const page = await context.newPage();
  const errors = []; page.on('pageerror',error=>errors.push(error.message));
  await context.route('https://**',route=>route.abort());
  try {
    await page.goto(base);
    await page.locator('#open-personal-library').click();
    await page.locator('#view-notes:not(.hidden)').waitFor();
    await page.locator('#note-new').click();
    await page.locator('#note-title').fill('阅读与记忆');
    await page.locator('#note-body').fill('# 思考的潮汐\n\n把看到的事物写下来，让它们在时间里相遇。\n\n## 长期的收藏\n\n一本书、一堂课、一个值得再次回访的想法。\n\n$$E=mc^2$$');
    await page.waitForFunction(()=>document.getElementById('note-save-state').textContent==='已保存');
    assert.equal((await page.request.get(`${base}/api/local/notebook`)).ok(),true);
    const title = await page.locator('#note-title').inputValue();
    await page.locator('#note-mode').click();
    await page.locator('#note-preview .katex').waitFor();
    await page.screenshot({path:'/tmp/sea-notes-desktop.png',fullPage:true});
    await page.locator('#note-star').click();
    await page.locator('[data-note-filter="starred"]').click();
    assert.ok(await page.locator('.note-list-row').count()>=1);
    await page.reload();
    await page.locator('#note-title').waitFor();
    assert.equal(await page.locator('#note-title').inputValue(),title);
    await page.locator('#note-body').fill('修订后的私人手记。');
    await page.waitForFunction(()=>document.getElementById('note-save-state').textContent==='已保存');
    await page.locator('#note-more').click();
    await page.getByRole('menuitem',{name:'历史版本'}).click();
    await page.locator('.note-history-row').first().waitFor();
    assert.ok(await page.locator('.note-history-row').count()>=1);
    await page.locator('.note-history-row').first().getByRole('button',{name:'恢复此版本'}).click();
    assert.match(await page.locator('#note-body').inputValue(),/思考的潮汐/);
    await page.locator('#note-more').click();
    await page.getByRole('menuitem',{name:'移入回收站'}).click();
    await page.locator('#message').getByRole('button',{name:'撤销'}).click();
    await page.locator('#note-title').waitFor();
    assert.equal(await page.locator('#note-title').inputValue(),title);
    await page.locator('.desktop-nav [data-view="search"]').click();
    await page.locator('#search').fill('潮汐');
    await page.locator('.personal-search-card').first().waitFor();
    await page.locator('.personal-search-card').first().click();
    assert.equal(await page.locator('#note-title').inputValue(),title);
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:'/tmp/sea-notes-mobile.png',fullPage:true});
    await page.locator('#note-index-back').click();
    assert.equal(await page.locator('#note-list').isVisible(),true);
    await page.setViewportSize({width:1440,height:960});
    await page.locator('.desktop-nav [data-view="settings"]').click();
    const [backup] = await Promise.all([page.waitForEvent('download'),page.locator('#notebook-backup').click()]);
    await backup.saveAs('/tmp/sea-notebook-backup.zip');
    await page.locator('#notebook-restore-file').setInputFiles('/tmp/sea-notebook-backup.zip');
    await page.waitForFunction(()=>document.getElementById('notebook-backup-status').textContent.startsWith('已导入 0'));
    assert.deepEqual(errors,[]);
    console.log('Notebook: offline rendering, autosave, restart, history, trash undo, search, mobile, backup and restore passed');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
